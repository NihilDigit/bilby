/**
 * 这个应用自己带的图标。
 *
 * 弹幕在这里,是因为 Material Symbols 里能读成"弹幕"的符号在播放页**已经各有主人**:
 * 气泡是评论,字幕框是字幕。借用任何一个都会让同一页里一个符号说两件事。
 *
 * 开与关是**两个字形**而不是一个字形换颜色:只靠颜色的话色觉障碍用户读不出当前是开还是关,
 * 风格指南 §2.6 对导航栏写的是同一条。
 */
object BilbyIcons {

    /**
     * 弹幕(开):小电视里一个"弹",右下角一个对勾。**哔哩哔哩官方客户端的那一个**,认得出来
     * 比自己画一个更要紧 —— 看过 B 站的人找弹幕开关,找的就是这个小电视。
     */
    val Danmaku: ImageVector by lazy { glyph("Danmaku", DanmakuOnPath) }

    /** 弹幕(关):同一个小电视,右下角换成禁止符号。 */
    val DanmakuOff: ImageVector by lazy { glyph("DanmakuOff", DanmakuOffPath) }

    /**
     * 弹幕设置:同一个小电视,右下角换成六角螺母。紧挨着开关放,两枚读得出是一对:
     * 通用的 ⚙ 放在那里,读成的是整个播放器的设置。
     */
    val DanmakuSettings: ImageVector by lazy { glyph("DanmakuSettings", DanmakuSettingsPath) }

    /**
     * 弹幕这件事本身,不带开关状态:统计行里的弹幕数、设置页的弹幕分组。小电视那一对带着对勾或
     * 禁止符号,放在"12.3万"前面读成"已开启",放在设置分组前面读成"这里是个开关"。
     *
     * 一块屏 + 三条错开飞过的字。**不用 Material 的字幕框**(PiliPlus 统计行用的是
     * `Icons.subtitles_outlined`):播放页控制条上的字幕按钮就是那个框,同一页里一个形状说两件事。
     * 三条线错开而不是左对齐,正是为了和字幕框分开 —— 后者的线贴着框底并且对齐,表达的是
     * "画面底下的一行字";弹幕要表达的是"从右往左穿过整块画面"。
     */
    val DanmakuCount: ImageVector by lazy { flyingLinesIcon() }
}

/**
 * 字形的轮廓来自 PiliPlus 的图标字体 `assets/fonts/custom_icon.ttf`(`dm_on` U+E802、
 * `dm_off` U+E801、`dm_settings` U+E803,GPL-3.0,与本仓库同一许可证),用 fontTools 的
 * SVGPathPen 原样导出。
 *
 * 字体坐标是 y 朝上、以基线为 0(em 1000,上沿 850),视口 y 朝下:整组沿 y 翻转再下移 850。
 * 填充而不是描边,`Icon` 的 tint 照样生效(它是一层 ColorFilter)。
 */
private fun glyph(name: String, pathData: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = GlyphEm,
        viewportHeight = GlyphEm,
    ).apply {
        group(scaleY = -1f, translationY = GlyphAscent) {
            addPath(
                pathData = PathParser().parsePathString(pathData).toNodes(),
                fill = SolidColor(Color.Black),
            )
        }
    }.build()

/** 全部用描边:内容是"框里有几条细线",填充版要把每条线画成细长矩形,坐标翻倍。 */
private fun flyingLinesIcon(): ImageVector =
    ImageVector.Builder(
        name = "DanmakuCount",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply {
        path(
            stroke = SolidColor(Color.Black),
            strokeLineWidth = FrameStroke,
            strokeLineJoin = StrokeJoin.Round,
            strokeLineCap = StrokeCap.Round,
        ) {
            // 屏框。上下留 5,左右留 3:弹幕是横着飞的,框比正方形扁一点才像一块画面。
            moveTo(5.5f, 5f)
            lineTo(18.5f, 5f)
            arcToRelative(2.5f, 2.5f, 0f, isMoreThanHalf = false, isPositiveArc = true, 2.5f, 2.5f)
            lineTo(21f, 16.5f)
            arcToRelative(2.5f, 2.5f, 0f, isMoreThanHalf = false, isPositiveArc = true, -2.5f, 2.5f)
            lineTo(5.5f, 19f)
            arcToRelative(2.5f, 2.5f, 0f, isMoreThanHalf = false, isPositiveArc = true, -2.5f, -2.5f)
            lineTo(3f, 7.5f)
            arcToRelative(2.5f, 2.5f, 0f, isMoreThanHalf = false, isPositiveArc = true, 2.5f, -2.5f)
            close()
        }
        path(
            stroke = SolidColor(Color.Black),
            strokeLineWidth = TextStroke,
            strokeLineCap = StrokeCap.Round,
        ) {
            moveTo(6.5f, 9f)
            lineTo(11.5f, 9f)
            moveTo(12.5f, 12f)
            lineTo(17.5f, 12f)
            moveTo(6.5f, 15f)
            lineTo(10.5f, 15f)
        }
    }.build()

